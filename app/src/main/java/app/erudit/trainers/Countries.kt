    val byCode: Map<String, Country> = all.associateBy { it.code }

    /**
     * Засчитывается ли [input] как одно из [accepted] названий. Прощаются регистр, «ё»,
     * дефисы и опечатка-другая, но только если ответ ближе к этой стране, чем к любой
     * другой из [others]: «Австрия» не сойдёт за «Австралию».
     */
    fun matches(input: String, accepted: List<String>, others: List<String>): Boolean {
        val n = normalize(input)
        if (n.isEmpty()) return false
        val best = accepted.minOf { AnswerMatcher.levenshtein(n, normalize(it)) }
        if (best == 0) return true
        val shortest = accepted.minOf { normalize(it).length }
        val tolerance = when {
            shortest <= 4 -> 0
            shortest <= 7 -> 1
            else -> 2
        }
        if (best > tolerance) return false
        val other = others.minOfOrNull { AnswerMatcher.levenshtein(n, normalize(it)) } ?: Int.MAX_VALUE
        return best < other
    }

    fun normalize(s: String): String =
        s.lowercase().replace('ё', 'е')
            .replace(Regex("[-–—’'`.,]"), " ")
            .replace(Regex("\\s+"), " ")
            .trim()
}
